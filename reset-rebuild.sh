#!/usr/bin/env bash
set -euo pipefail

# -----------------------------------------------------------------
# Load environment from .env (if it exists)
# -----------------------------------------------------------------
if [[ -f .env ]]; then
  echo "Loading environment from .env"
  # Export all variables defined in .env
  set -a
  source .env
  set +a
else
  echo "Warning: .env file not found. Proceeding with existing environment."
fi

# -----------------------------------------------------------------
# Default values (used only if the variable is unset or empty)
# -----------------------------------------------------------------
: "${DB_NAME:=wordpress}"
: "${DB_USER:=root}"
: "${DB_PASSWORD:=}"
: "${DB_HOST:=db}"
: "${DB_PREFIX:=wp_}"
: "${WP_HOME:=http://localhost:8080}"
: "${WP_SITEURL:=http://localhost:8080}"
: "${WP_DEBUG:=true}"
: "${WP_DEBUG_LOG:=true}"
: "${WP_DEBUG_DISPLAY:=true}"
: "${WP_REDIS_HOST:=redis}"
: "${WP_REDIS_PORT:=6379}"
: "${WP_CACHE_KEY_SALT:=${DB_NAME}}"
: "${WP_SITE_TITLE:=My WordPress Site}"
: "${WP_ADMIN_USER:=admin}"
: "${WP_ADMIN_PASSWORD:=admin123}"
: "${WP_ADMIN_EMAIL:=admin@example.com}"
: "${WP_DISCOURSE_SEARCH_ENGINES:=true}"
: "${ENVIRONMENT:=development}"

# -----------------------------------------------------------------
# Warn if critical admin variables are empty after applying defaults
# -----------------------------------------------------------------
if [[ -z "${WP_ADMIN_PASSWORD}" || "${WP_ADMIN_PASSWORD}" == "admin123" ]]; then
  echo "Warning: WP_ADMIN_PASSWORD is empty or using default. Please set a strong password in .env"
fi
if [[ -z "${WP_ADMIN_EMAIL}" || "${WP_ADMIN_EMAIL}" == "admin@example.com" ]]; then
  echo "Warning: WP_ADMIN_EMAIL is empty or using default. Please set a real e‑mail in .env"
fi

# -----------------------------------------------------------------
# Helper to generate random salts for wp-config.php
# -----------------------------------------------------------------
generate_salt() {
  head -c32 /dev/urandom | base64 | tr -d '\n' | cut -c1-64
}

# Generate six salts
SALT1=$(generate_salt)
SALT2=$(generate_salt)
SALT3=$(generate_salt)
SALT4=$(generate_salt)
SALT5=$(generate_salt)
SALT6=$(generate_salt)

# -----------------------------------------------------------------
# Generate wp-config.php – reads secrets via getenv() so they never
# appear in the file itself.
# -----------------------------------------------------------------
echo "Generating wp-config.php..."
cat > wp-config.php <<EOF
<?php
/**
 * WordPress Configuration Docker
 * Generated by reset-rebuild.sh
 */

// ** MySQL settings – read from environment for security ** //
define( 'DB_NAME',     getenv('WORDPRESS_DB_NAME')     ?: '' );
define( 'DB_USER',     getenv('WORDPRESS_DB_USER')     ?: '' );
define( 'DB_PASSWORD', getenv('WORDPRESS_DB_PASSWORD') ?: '' );
define( 'DB_HOST',     getenv('WORDPRESS_DB_HOST')     ?: '' );
define( 'DB_CHARSET', 'utf8mb4' );
define( 'DB_COLLATE', '' );

// Handle SSL reverse proxy (Cloudflare Tunnel)
if (isset(\$_SERVER['HTTP_X_FORWARDED_PROTO']) && 
    strtolower(\$_SERVER['HTTP_X_FORWARDED_PROTO']) === 'https') {
    \$_SERVER['HTTPS'] = 'on';
}

/**#@+
 * Authentication Unique Keys and Salts.
 */
define( 'AUTH_KEY',         '${SALT1}' );
define( 'SECURE_AUTH_KEY',  '${SALT2}' );
define( 'LOGGED_IN_KEY',    '${SALT3}' );
define( 'NONCE_KEY',        '${SALT4}' );
define( 'AUTH_SALT',        '${SALT5}' );
define( 'SECURE_AUTH_SALT', '${SALT6}' );
/**#@-*/

/**
 * WordPress Database Table prefix.
 */
\$table_prefix = getenv('WORDPRESS_DB_PREFIX') ?: 'wp_';

// Redis Object Cache settings (if using)
if ( getenv('WP_REDIS_HOST') ) {
    define( 'WP_CACHE_KEY_SALT', getenv('WP_CACHE_KEY_SALT') ?: '' );
    define( 'WP_REDIS_HOST',     getenv('WP_REDIS_HOST')     ?: '' );
    define( 'WP_REDIS_PORT',     getenv('WP_REDIS_PORT')     ?: 6379 );
}

/**
 * Debugging mode.
 */
define( 'WP_DEBUG',     filter_var(getenv('WP_DEBUG'),     FILTER_VALIDATE_BOOLEAN) ?: false );
define( 'WP_DEBUG_LOG', filter_var(getenv('WP_DEBUG_LOG'), FILTER_VALIDATE_BOOLEAN) ?: false );
define( 'WP_DEBUG_DISPLAY', filter_var(getenv('WP_DEBUG_DISPLAY'), FILTER_VALIDATE_BOOLEAN) ?: false );
define( 'SCRIPT_DEBUG', true );

/* That's all, stop editing! Happy publishing. */
if ( ! defined( 'ABSPATH' ) ) {
	define( 'ABSPATH', __DIR__ . '/' );
}
require_once ABSPATH . 'wp-settings.php';
EOF

echo "wp-config.php generated."

# -----------------------------------------------------------------
# Clean start: remove all containers, networks, volumes
# -----------------------------------------------------------------
echo "Stopping and removing containers, networks, and volumes..."
docker compose down -v --remove-orphans
echo "Pruning unused Docker resources (volumes, networks)..."
docker system prune -f --volumes

# -----------------------------------------------------------------
# Build and start the stack
# -----------------------------------------------------------------
echo "Building and starting containers..."
docker compose build --no-cache
docker compose up --build -d

echo "Waiting for services to be healthy..."
sleep 15   # give MySQL, Redis, etc. a moment to start

# -----------------------------------------------------------------
# WordPress core installation
# -----------------------------------------------------------------
echo "Installing WordPress core..."
docker exec wpimgplugin-wordpress-1 wp core install \
  --url="${WP_HOME}" \
  --title="${WP_SITE_TITLE}" \
  --admin_user="${WP_ADMIN_USER}" \
  --admin_password="${WP_ADMIN_PASSWORD}" \
  --admin_email="${WP_ADMIN_EMAIL}" \
  --skip-email \
  --path=/var/www/html

echo "Updating site title..."
docker exec wpimgplugin-wordpress-1 wp option update blogname "${WP_SITE_TITLE}" --path=/var/www/html

echo "Updating admin user credentials (password & e‑mail only; login cannot be changed after install)..."
docker exec wpimgplugin-wordpress-1 wp user update 1 \
  --user_pass="${WP_ADMIN_PASSWORD}" \
  --user_email="${WP_ADMIN_EMAIL}" \
  --path=/var/www/html

# -----------------------------------------------------------------
# Search‑engine visibility
# -----------------------------------------------------------------
if [[ "${WP_DISCOURSE_SEARCH_ENGINES}" == "true" ]]; then
  echo "Discouraging search engines from indexing this site..."
  docker exec wpimgplugin-wordpress-1 wp option update blog_public 0 --path=/var/www/html
else
  echo "Allowing search engines to index this site..."
  docker exec wpimgplugin-wordpress-1 wp option update blog_public 1 --path=/var/www/html
fi

# -----------------------------------------------------------------
# Redis Object Cache plugin
# -----------------------------------------------------------------
echo "Installing and activating Redis Object Cache plugin..."
docker exec wpimgplugin-wordpress-1 wp plugin install \
  /tmp/redis-cache.zip \
  --activate \
  --path=/var/www/html \
  --url="${WP_HOME}" 2>/dev/null || {
    # Fallback: download fresh zip if the local copy is missing/old
    docker exec wpimgplugin-wordpress-1 curl -L -o /tmp/redis-cache.zip \
      https://downloads.wordpress.org/plugin/redis-cache.latest-stable.zip
    docker exec wpimgplugin-wordpress-1 wp plugin install \
      /tmp/redis-cache.zip \
      --activate \
      --path=/var/www/html \
      --url="${WP_HOME}"
  }

# -----------------------------------------------------------------
# Additional plugins from wordpress.org (edit the array to add more)
# -----------------------------------------------------------------
PLUGINS_TO_INSTALL=(
  # "akismet"
  # "contact-form-7"
)

for plugin in "${PLUGINS_TO_INSTALL[@]}"; do
  echo "Installing and activating plugin: $plugin"
  docker exec wpimgplugin-wordpress-1 wp plugin install "$plugin" \
    --activate \
    --path=/var/www/html \
    --url="${WP_HOME}" || {
      echo "Failed to install $plugin via wp‑cli; trying download..."
      docker exec wpimgplugin-wordpress-1 wp plugin install "$plugin" \
        --activate \
        --path=/var/www/html \
        --url="${WP_HOME}" --skip-deps || true
    }
done

# -----------------------------------------------------------------
# Local plugin: WebP Studio (already present in image)
# -----------------------------------------------------------------
echo "Activating local plugin: webp-studio"
docker exec wpimgplugin-wordpress-1 wp plugin activate webp-studio \
  --path=/var/www/html \
  --url="${WP_HOME}" || {
    echo "Failed to activate local plugin webp-studio"
  }

# -----------------------------------------------------------------
# Ensure plugin defaults exist so the settings page is fully populated.
# Activation normally does this, but the option is only written when the
# plugin is activated for the first time on a given database.
# -----------------------------------------------------------------
echo "Seeding plugin options..."
docker exec wpimgplugin-wordpress-1 wp eval "
\$existing = get_option( 'wp_image_webp_converter_settings', false );
if ( false === \$existing ) {
    update_option( 'wp_image_webp_converter_settings', array(
        'enabled'          => 1,
        'quality'          => 80,
        'delete_original'  => 1,
        'process_existing' => 0,
        'activity_log'     => 1,
    ) );
    echo 'Defaults created.';
} else {
    // Backfill activity_log for options written before that key existed.
    if ( ! array_key_exists( 'activity_log', \$existing ) ) {
        \$existing['activity_log'] = 1;
        update_option( 'wp_image_webp_converter_settings', \$existing );
        echo 'activity_log backfilled.';
    } else {
        echo 'Options already present.';
    }
}
" --path=/var/www/html --url="${WP_HOME}"

# -----------------------------------------------------------------
# Convert any existing images to WebP.
#
# Conversion is delegated to the plugin's own background runner rather than
# reimplemented here. This block used to call WebP_Converter_For_News::
# convert_to_webp(), which no longer exists, so it was silently doing nothing.
# -----------------------------------------------------------------
echo "Checking for images pending WebP conversion..."
# Only the final numeric line is the count; earlier lines are plugin notices.
PENDING=$(docker exec wpimgplugin-wordpress-1 wp eval "
global \$wpdb;
echo 'PENDING_COUNT=' . (int) \$wpdb->get_var( \"SELECT COUNT(*) FROM \$wpdb->posts WHERE post_type = 'attachment' AND post_mime_type IN ('image/jpeg','image/png','image/gif')\" );
" --path=/var/www/html --url="${WP_HOME}" \
  | sed -n 's/.*PENDING_COUNT=\([0-9]\{1,\}\).*/\1/p' | tail -1)
PENDING="${PENDING:-0}"

if [ "${PENDING:-0}" -gt 0 ]; then
  echo "  ${PENDING} image(s) pending; queueing background conversion."
  docker exec wpimgplugin-wordpress-1 wp eval "
\$o = new WP_Image_WebP_Converter();
\$r = new ReflectionClass( 'WP_Image_WebP_Converter' );
\$m = \$r->getMethod( 'start_run' );
\$m->setAccessible( true );
\$m->invoke( \$o );
echo 'Background run queued. It completes via WP-Cron; the settings page shows progress.';
" --path=/var/www/html --url="${WP_HOME}"
else
  echo "  Nothing pending."
fi

# -----------------------------------------------------------------
# Enable Redis Object Cache and verify
# -----------------------------------------------------------------
echo "Enabling Redis Object Cache..."
docker exec wpimgplugin-wordpress-1 wp redis enable \
  --path=/var/www/html \
  --url="${WP_HOME}"

echo "Verifying Redis Object Cache status..."
docker exec wpimgplugin-wordpress-1 wp redis status \
  --path=/var/www/html \
  --url="${WP_HOME}"

# -----------------------------------------------------------------
# Import seed images
#
# This script runs `docker compose down -v`, which destroys the WordPress volume and
# therefore every uploaded file. Without this step the site always comes back with an
# empty media library, which makes it impossible to verify the plugin against real
# content.
#
# The image binaries are not tracked in git (see .gitignore): they weigh ~17 MB and would
# dominate the history for no benefit, since they are development fixtures rather than
# plugin assets or release artifacts. seed.sh therefore fetches them on demand from Lorem
# Picsum using fixed image IDs, so a fresh clone receives the same set of photos. Once
# imported they are ordinary WordPress attachments. See seed-images/README.md for
# provenance and licensing.
#
# --download is mandatory here, not optional: with the binaries untracked there is
# nothing local left to import, and seed.sh aborts when it finds no images. It also
# regenerates the PNG and GIF through GD inside the running container, which is why this
# block has to stay after `docker compose up`.
# -----------------------------------------------------------------
echo "Importing seed images..."
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
if [ -x "${SCRIPT_DIR}/seed-images/seed.sh" ]; then
  WP_CONTAINER=wpimgplugin-wordpress-1 \
  WP_HOME="${WP_HOME}" \
    "${SCRIPT_DIR}/seed-images/seed.sh" --download || echo "Seed import reported problems; continuing."
else
  echo "  seed-images/seed.sh not found or not executable; skipping."
fi

# -----------------------------------------------------------------
# Final summary
# -----------------------------------------------------------------
echo "Done! WordPress should be accessible at ${WP_HOME}"
echo "Admin credentials:"
echo "  Username: ${WP_ADMIN_USER}"
echo "  Password: ${WP_ADMIN_PASSWORD} (store securely!)"
echo "  Email:    ${WP_ADMIN_EMAIL}"
echo "  Site Title: ${WP_SITE_TITLE}"
echo "  Search engine visibility: ${WP_DISCOURSE_SEARCH_ENGINES}"
